//! The Diplomat (ὁ Διπλωμάτης) - TypeScript Interface Generator
//!
//! This module implements the "Diplomat" tool, which inspects the type definitions
//! (`εἶδος`) and trait definitions (`χαρακτήρ`) within a ΓΛΩΣΣΑ program and translates
//! them into TypeScript `interface` declarations.
//!
//! # Purpose
//!
//! A diplomat bridges different cultures. In modern systems, we often need our backend
//! data structures (written in Glossa) to be understood by frontend applications (written in TypeScript).
//! This tool automatically generates `.d.ts`-compatible declarations, ensuring
//! type safety across the language barrier.
//!
//! # How it Works
//!
//! The [`run_diplomat`] function orchestrates the process:
//! 1. Parses and semantically analyzes the source code.
//! 2. Scans the Abstract Syntax Tree for `TypeDefinition` and `TraitDefinition` nodes.
//! 3. Maps ΓΛΩΣΣΑ types (`ἀριθμοῦ`, `ὀνόματος`, etc.) to TypeScript types (`number`, `string`, etc.).
//! 4. Outputs formatted TypeScript code to the terminal using a stylish, colorful table.

use crate::semantic::{AnalyzedStatement, GlossaType};
use crate::tools::runner::load_source;
use crate::tools::ui::Status;
use comfy_table::{Attribute, Cell, Color, Table, presets};
use crossterm::style::Stylize;
use miette::Result;
use std::fmt::Write;
use std::path::Path;

/// Runs the Diplomat tool to generate TypeScript interfaces from Glossa types and traits.
///
/// The Diplomat (Διπλωμάτης) tool reads the provided source file, compiles it, and automatically
/// generates corresponding TypeScript `interface` statements for any type or trait definitions found.
///
/// # Examples
///
/// ```rust,no_run
/// use glossa::tools::diplomat::run_diplomat;
/// use std::path::Path;
///
/// let input = Path::new("types.γλ");
/// if let Err(e) = run_diplomat(&input) {
///     eprintln!("TypeScript generation failed: {}", e);
/// }
/// ```
///
/// # Errors
///
/// Returns a [`miette::Result`] if the file cannot be read, or if there is a parsing
/// or semantic analysis error during compilation.
pub fn run_diplomat(input: &Path) -> Result<()> {
    if !input.exists() {
        return Err(miette::miette!("Ἀρχεῖον οὐχ εὑρέθη: {}", input.display()));
    }

    let status = Status::start_with_symbol("Διπλωμάτης (Generating TypeScript)", "🤝");

    let source = match load_source(input) {
        Ok(s) => s,
        Err(e) => {
            status.error("Σφάλμα ἀρχείου (File Error)");
            return Err(e);
        }
    };

    let program = match crate::tools::runner::analyze_source(&source) {
        Ok(p) => p,
        Err(e) => {
            status.error("Σφάλμα ἀναλύσεως (Analysis Error)");
            return Err(e);
        }
    };

    status.success();

    let mut output = String::new();
    output.push_str("/**\n");
    output.push_str(" * Auto-generated by ΓΛΩΣΣΑ Diplomat\n");
    output.push_str(" */\n\n");

    for stmt in &program.statements {
        match stmt {
            AnalyzedStatement::TypeDefinition { name, fields } => {
                let _ = writeln!(output, "export interface {} {{", name);
                for (field_name, field_type) in fields {
                    let ts_type = glossa_type_to_ts(field_type);
                    // Check if it's an option to make the field optional
                    if let GlossaType::Option(_) = field_type {
                        let _ = writeln!(output, "    {}?: {};", field_name, ts_type);
                    } else {
                        let _ = writeln!(output, "    {}: {};", field_name, ts_type);
                    }
                }
                output.push_str("}\n\n");
            }
            AnalyzedStatement::TraitDefinition { name, methods } => {
                let _ = writeln!(output, "export interface {} {{", name);
                for method in methods {
                    let _ = write!(output, "    {}(", method.name);
                    for (i, (param_name, param_type)) in method.params.iter().enumerate() {
                        let comma = if i < method.params.len() - 1 {
                            ", "
                        } else {
                            ""
                        };
                        let _ = write!(
                            output,
                            "{}: {}{}",
                            param_name,
                            glossa_type_to_ts(param_type),
                            comma
                        );
                    }
                    let ret_type = match &method.return_type {
                        Some(t) => glossa_type_to_ts(t),
                        None => "void".to_string(),
                    };
                    let _ = writeln!(output, "): {};", ret_type);
                }
                output.push_str("}\n\n");
            }
            _ => {}
        }
    }

    println!();
    println!("   {}", "Γ Λ Ω Σ Σ Α   D I P L O M A T".bold().cyan());
    println!("   {}", "TypeScript Interfaces".italic().dim());
    println!();

    let mut table = Table::new();
    table.load_preset(presets::UTF8_FULL);

    table.set_header(vec![
        Cell::new("TypeScript Definitions")
            .add_attribute(Attribute::Bold)
            .fg(Color::Cyan),
    ]);

    let formatted_code = format!("```typescript\n{}\n```", output.trim());
    table.add_row(vec![Cell::new(formatted_code)]);

    println!("{table}");
    println!();

    Ok(())
}

fn glossa_type_to_ts(g_type: &GlossaType) -> String {
    match g_type {
        GlossaType::Number => "number".to_string(),
        GlossaType::String => "string".to_string(),
        GlossaType::Boolean => "boolean".to_string(),
        GlossaType::List(inner) => format!("Array<{}>", glossa_type_to_ts(inner)),
        GlossaType::Set(inner) => format!("Set<{}>", glossa_type_to_ts(inner)),
        GlossaType::Map(k, v) => format!("Map<{}, {}>", glossa_type_to_ts(k), glossa_type_to_ts(v)),
        GlossaType::Option(inner) => glossa_type_to_ts(inner), // Optionality is handled at the field level
        GlossaType::Result(ok, err) => format!(
            "Result<{}, {}>",
            glossa_type_to_ts(ok),
            glossa_type_to_ts(err)
        ),
        GlossaType::Struct { name, .. } => name.to_string(),
        GlossaType::Function { params, returns } => {
            let mut param_str = String::new();
            for (i, p) in params.iter().enumerate() {
                let comma = if i < params.len() - 1 { ", " } else { "" };
                let _ = write!(param_str, "arg{}: {}{}", i, glossa_type_to_ts(p), comma);
            }
            format!("({}) => {}", param_str, glossa_type_to_ts(returns))
        }
        GlossaType::Unit => "void".to_string(),
        GlossaType::Unknown => "any".to_string(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_glossa_type_to_ts() {
        assert_eq!(glossa_type_to_ts(&GlossaType::Number), "number");
        assert_eq!(glossa_type_to_ts(&GlossaType::String), "string");
        assert_eq!(glossa_type_to_ts(&GlossaType::Boolean), "boolean");
        assert_eq!(
            glossa_type_to_ts(&GlossaType::List(Box::new(GlossaType::Number))),
            "Array<number>"
        );
        assert_eq!(
            glossa_type_to_ts(&GlossaType::Set(Box::new(GlossaType::String))),
            "Set<string>"
        );
        assert_eq!(
            glossa_type_to_ts(&GlossaType::Map(
                Box::new(GlossaType::String),
                Box::new(GlossaType::Number)
            )),
            "Map<string, number>"
        );
        assert_eq!(
            glossa_type_to_ts(&GlossaType::Option(Box::new(GlossaType::Number))),
            "number"
        );
        assert_eq!(glossa_type_to_ts(&GlossaType::Unknown), "any");
        assert_eq!(glossa_type_to_ts(&GlossaType::Unit), "void");

        let struct_type = GlossaType::Struct {
            name: "User".into(),
            gender: crate::morphology::Gender::Masculine,
            fields: vec![],
        };
        assert_eq!(glossa_type_to_ts(&struct_type), "User");

        let func_type = GlossaType::Function {
            params: vec![GlossaType::Number, GlossaType::String],
            returns: Box::new(GlossaType::Boolean),
        };
        assert_eq!(
            glossa_type_to_ts(&func_type),
            "(arg0: number, arg1: string) => boolean"
        );
    }

    #[test]
    fn test_run_diplomat_file_not_found() {
        use std::path::PathBuf;
        let path = PathBuf::from("non_existent_file.γλ");
        let result = run_diplomat(&path);
        assert!(result.is_err());
        assert!(result.unwrap_err().to_string().contains("οὐχ εὑρέθη"));
    }

    #[test]
    fn test_run_diplomat_empty_file() {
        let dir = tempfile::tempdir().unwrap();
        let input_path = dir.path().join("test_diplomat_empty.γλ");
        {
            use std::io::Write;
            let mut f = std::fs::File::create(&input_path).unwrap();
            f.write_all("ξ 1 ἔστω.\n".as_bytes()).unwrap();
        }

        // Run the command to ensure the empty logic is hit without panicking
        let result = run_diplomat(&input_path);
        assert!(result.is_ok());
    }
}
